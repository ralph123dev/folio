create table if not exists public.freelancer_search_events (
  id bigint generated by default as identity primary key,
  visitor_id text not null,
  freelancer_id uuid not null references public.freelancers(id) on delete cascade,
  profile_owner_id uuid not null references public.profils(id) on delete cascade,
  search_query text not null,
  profession text,
  search_day date not null default current_date,
  created_at timestamp with time zone not null default timezone('utc'::text, now()),
  unique (visitor_id, freelancer_id, search_query, search_day)
);

do $$
begin
  if not exists (
    select 1 from pg_publication p
    join pg_publication_rel pr on pr.prpubid = p.oid
    join pg_class c on c.oid = pr.prrelid
    join pg_namespace n on n.oid = c.relnamespace
    where p.pubname = 'supabase_realtime' and n.nspname = 'public' and c.relname = 'freelancer_search_events'
  ) then
    alter publication supabase_realtime add table public.freelancer_search_events;
  end if;
end
$$;

alter table public.freelancer_search_events enable row level security;

drop policy if exists "Les visiteurs peuvent enregistrer des recherches freelancers." on public.freelancer_search_events;
create policy "Les visiteurs peuvent enregistrer des recherches freelancers."
  on public.freelancer_search_events for insert
  to anon, authenticated
  with check (char_length(trim(search_query)) > 0);

drop policy if exists "Les propriétaires peuvent voir leurs recherches freelancers." on public.freelancer_search_events;
create policy "Les propriétaires peuvent voir leurs recherches freelancers."
  on public.freelancer_search_events for select
  to authenticated
  using (auth.uid() = profile_owner_id);

create or replace function public.get_search_detection_stats(target_user_id uuid)
returns table (profession text, search_query text, search_count bigint)
language sql
security definer
set search_path = public
as $$
  select
    e.profession,
    e.search_query,
    count(distinct e.visitor_id)::bigint as search_count
  from public.freelancer_search_events e
  where e.profile_owner_id = target_user_id
  group by e.profession, e.search_query
  order by search_count desc, e.profession asc;
$$;

revoke all on function public.get_search_detection_stats(uuid) from public;
grant execute on function public.get_search_detection_stats(uuid) to authenticated;