create table if not exists public.contact_boost_contacts (
  id bigint generated by default as identity primary key,
  name text not null default 'Contact',
  email text,
  phone text,
  whatsapp_phone text,
  sector text,
  created_at timestamptz not null default now(),
  constraint contact_boost_contacts_has_contact check (nullif(trim(coalesce(email, '') || coalesce(phone, '')), '') is not null)
);

create index if not exists contact_boost_contacts_sector_idx
  on public.contact_boost_contacts (sector, id);

alter table public.contact_boost_contacts enable row level security;
revoke all on table public.contact_boost_contacts from anon, authenticated;

create table if not exists public.contact_boost_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  sector text not null,
  contact_count integer not null,
  created_at timestamptz not null default now()
);

create index if not exists contact_boost_subscriptions_user_idx
  on public.contact_boost_subscriptions (user_id, created_at desc);

alter table public.contact_boost_subscriptions enable row level security;
revoke all on table public.contact_boost_subscriptions from anon, authenticated;

create or replace function public.subscribe_contact_boost(
  target_user_id uuid,
  target_sector text,
  contact_count integer,
  boost_cost numeric
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  user_profile public.profils;
  expected_cost numeric(12, 2);
begin
  if auth.uid() is null or auth.uid() <> target_user_id then
    return jsonb_build_object('success', false, 'message', 'Vous n''êtes pas autorisé à effectuer cette souscription.');
  end if;

  expected_cost := case contact_count
    when 300 then 100
    when 1300 then 200
    when 15000 then 300
    when 31000 then 1000
    when 10000 then 2100
    else null
  end;

  if expected_cost is null or boost_cost <> expected_cost then
    return jsonb_build_object('success', false, 'message', 'Forfait de contacts invalide.');
  end if;

  select * into user_profile
  from public.profils
  where id = target_user_id
  for update;

  if not found then
    return jsonb_build_object('success', false, 'message', 'Profil introuvable.');
  end if;

  if coalesce(user_profile.solde, 0) < expected_cost then
    return jsonb_build_object('success', false, 'message', format('Solde insuffisant. Il vous faut %s F CFA.', expected_cost));
  end if;

  update public.profils
  set solde = coalesce(solde, 0) - expected_cost
  where id = target_user_id;

  insert into public.contact_boost_subscriptions (user_id, sector, contact_count)
  values (target_user_id, target_sector, contact_count);

  return jsonb_build_object('success', true, 'message', 'Forfait de contacts souscrit avec succès.', 'new_solde', user_profile.solde - expected_cost, 'sector', target_sector, 'contact_count', contact_count);
end;
$$;

create or replace function public.get_contact_boost_contacts(
  target_sector text,
  requested_count integer
)
returns table (name text, email text, phone text, "whatsappPhone" text)
language plpgsql
security definer
set search_path = public
as $$
declare
  allowed_count integer;
begin
  select s.contact_count into allowed_count
  from public.contact_boost_subscriptions s
  where s.user_id = auth.uid() and s.sector = target_sector
  order by s.created_at desc
  limit 1;

  if allowed_count is null then
    return;
  end if;

  return query
  select c.name, c.email, c.phone, c.whatsapp_phone
  from public.contact_boost_contacts c
  where c.sector = target_sector or c.sector is null
  order by c.id
  limit least(greatest(requested_count, 0), allowed_count);
end;
$$;

revoke all on function public.get_contact_boost_contacts(text, integer) from public;
grant execute on function public.get_contact_boost_contacts(text, integer) to authenticated;